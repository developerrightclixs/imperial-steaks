/* ============================================================================
   Imperial Steaks - main.js
   Minimal vanilla JavaScript. Four small jobs:
     1. toggle the mobile navigation
     2. drive the product carousel's prev/next arrows
     3. reveal elements as they scroll into view
     4. sticky-header state + back-to-top control
   ----------------------------------------------------------------------------
   No libraries, no frameworks, no build step. Every piece of page content is
   real HTML - nothing here is generated by JavaScript, so the WordPress build
   can drop this file entirely. Elementor replaces all four natively: Nav Menu
   (mobile dropdown), Image Carousel (arrows), Motion Effects > Entrance
   Animation (reveals), and the Back to Top widget.

   Everything degrades gracefully with JavaScript off: the menu stays a plain
   list, the carousel is still a native horizontal scroll area (swipe, trackpad,
   shift+wheel and keyboard all work), and no content is ever hidden - the
   reveal styles are scoped behind a `reveal-on` class that only this file adds.
   ========================================================================== */

/* --- 1. Mobile navigation --------------------------------------------------- */
(function () {
  'use strict';

  var toggle = document.querySelector('.imperial-nav-toggle');
  var nav = document.querySelector('.imperial-nav');

  if (!toggle || !nav) {
    return;
  }

  function setOpen(isOpen) {
    nav.classList.toggle('is-open', isOpen);
    toggle.setAttribute('aria-expanded', isOpen ? 'true' : 'false');
  }

  toggle.addEventListener('click', function () {
    setOpen(!nav.classList.contains('is-open'));
  });

  /* Close the menu on Escape and return focus to the toggle button. */
  document.addEventListener('keydown', function (event) {
    if (event.key === 'Escape' && nav.classList.contains('is-open')) {
      setOpen(false);
      toggle.focus();
    }
  });

  /* If the viewport grows past the tablet breakpoint, reset the menu state so
     the desktop layout is never left with a stale "is-open" class. */
  window.addEventListener('resize', function () {
    if (window.innerWidth > 1024 && nav.classList.contains('is-open')) {
      setOpen(false);
    }
  });
})();


/* --- 2. Product carousel arrows --------------------------------------------
   Works on any element marked [data-carousel] containing a [data-carousel-track]
   plus [data-carousel-prev] / [data-carousel-next] buttons, so a second
   carousel can be added later without touching this file.
   -------------------------------------------------------------------------- */
(function () {
  'use strict';

  var carousels = document.querySelectorAll('[data-carousel]');
  if (!carousels.length) {
    return;
  }

  Array.prototype.forEach.call(carousels, function (carousel) {
    var track = carousel.querySelector('[data-carousel-track]');
    var prev = carousel.querySelector('[data-carousel-prev]');
    var next = carousel.querySelector('[data-carousel-next]');

    if (!track || !prev || !next) {
      return;
    }

    /* Scroll by one slide, including the grid gap, so slides stay aligned
       with the scroll-snap points. */
    function step() {
      var slide = track.firstElementChild;
      if (!slide) {
        return track.clientWidth;
      }
      var styles = window.getComputedStyle(track);
      var gap = parseFloat(styles.columnGap || styles.gap) || 0;
      return slide.getBoundingClientRect().width + gap;
    }

    /* Enable/disable the arrows at the ends, and hide both if the track does
       not overflow (wide screens, or a short product list). */
    function update() {
      var max = track.scrollWidth - track.clientWidth;
      var scrollable = max > 1;

      prev.hidden = !scrollable;
      next.hidden = !scrollable;

      if (!scrollable) {
        return;
      }

      /* 1px tolerance: fractional widths rarely land exactly on the end. */
      prev.disabled = track.scrollLeft <= 1;
      next.disabled = track.scrollLeft >= max - 1;
    }

    function scrollBy(direction) {
      var reduced = window.matchMedia
        && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
      track.scrollBy({
        left: direction * step(),
        behavior: reduced ? 'auto' : 'smooth'
      });
    }

    prev.addEventListener('click', function () { scrollBy(-1); });
    next.addEventListener('click', function () { scrollBy(1); });

    /* Left/right arrow keys when the track itself has focus. */
    track.addEventListener('keydown', function (event) {
      if (event.key === 'ArrowRight') {
        event.preventDefault();
        scrollBy(1);
      } else if (event.key === 'ArrowLeft') {
        event.preventDefault();
        scrollBy(-1);
      }
    });

    track.addEventListener('scroll', update, { passive: true });
    window.addEventListener('resize', update);

    /* Images change the track width as they load, so recheck then too. */
    window.addEventListener('load', update);
    update();
  });
})();


/* --- 3. Scroll reveals -------------------------------------------------------
   Adds `.is-visible` to [data-reveal] elements as they enter the viewport.

   The hidden state lives behind `html.reveal-on`, which is added here, so if
   this file fails to load or JavaScript is off, nothing is ever hidden. If
   IntersectionObserver is missing, or the user prefers reduced motion, every
   element is revealed immediately instead.

   Not migrated to WordPress: Elementor's Entrance Animation controls replace it.
   -------------------------------------------------------------------------- */
(function () {
  'use strict';

  var targets = document.querySelectorAll('[data-reveal]');
  if (!targets.length) {
    return;
  }

  function revealAll() {
    Array.prototype.forEach.call(targets, function (el) {
      el.classList.add('is-visible');
    });
  }

  var reduced = window.matchMedia
    && window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  if (reduced || !('IntersectionObserver' in window)) {
    document.documentElement.classList.add('reveal-on');
    revealAll();
    return;
  }

  /* Only now is it safe to hide them. */
  document.documentElement.classList.add('reveal-on');

  function show(el) {
    el.classList.add('is-visible');
    observer.unobserve(el);                    /* reveal once, then stop watching */
  }

  /* threshold 0: any sliver of the element counts. A threshold above zero can
     never be met by an element taller than the viewport, which would leave it
     permanently hidden - exactly the failure this feature must not have. */
  var observer = new IntersectionObserver(function (entries) {
    entries.forEach(function (entry) {
      if (entry.isIntersecting) {
        show(entry.target);
      }
    });
  }, {
    /* Start slightly before the element arrives so the motion finishes about
       when it is properly in view. */
    rootMargin: '0px 0px -6% 0px',
    threshold: 0
  });

  Array.prototype.forEach.call(targets, function (el) {
    observer.observe(el);
  });

  /* Belt and braces: a throttled sweep that reveals anything already within the
     viewport. IntersectionObserver handles the normal case; this guarantees
     correctness if it is throttled, deferred, or never fires at all. Content
     must never be left invisible because an optional effect misbehaved. */
  var ticking = false;

  function sweep() {
    var vh = window.innerHeight || document.documentElement.clientHeight;
    Array.prototype.forEach.call(targets, function (el) {
      if (el.classList.contains('is-visible')) {
        return;
      }
      var box = el.getBoundingClientRect();
      if (box.top < vh * 0.98 && box.bottom > 0) {
        show(el);
      }
    });
    ticking = false;
  }

  function queueSweep() {
    if (!ticking) {
      window.requestAnimationFrame(sweep);
      ticking = true;
    }
  }

  window.addEventListener('scroll', queueSweep, { passive: true });
  window.addEventListener('resize', queueSweep);
  window.addEventListener('load', sweep);
  sweep();
})();


/* --- 4. Sticky-header state + back to top ----------------------------------
   The header tightens once the page scrolls; the back-to-top control appears
   after a screenful. Both are single-class toggles driven by one scroll
   listener, throttled with requestAnimationFrame.

   Not migrated: Elementor's sticky Scroll Effects and Back to Top widget.
   -------------------------------------------------------------------------- */
(function () {
  'use strict';

  var header = document.querySelector('.imperial-header');
  var toTop = document.querySelector('.imperial-to-top');

  if (!header && !toTop) {
    return;
  }

  var ticking = false;

  function update() {
    var y = window.pageYOffset || document.documentElement.scrollTop;

    if (header) {
      header.classList.toggle('is-scrolled', y > 40);
    }
    if (toTop) {
      toTop.classList.toggle('is-visible', y > window.innerHeight * 0.9);
    }
    ticking = false;
  }

  window.addEventListener('scroll', function () {
    if (!ticking) {
      window.requestAnimationFrame(update);
      ticking = true;
    }
  }, { passive: true });

  if (toTop) {
    toTop.addEventListener('click', function () {
      var reduced = window.matchMedia
        && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
      window.scrollTo({ top: 0, behavior: reduced ? 'auto' : 'smooth' });
    });
  }

  update();
})();
